// 언어 이름(화면 언어 기준)
const NAMES_RU = { ko: 'Корейский', ru: 'Русский', en: 'Английский', uk: 'Украинский', kk: 'Казахский', uz: 'Узбекский',
  mn: 'Монгольский', zh: 'Китайский', ja: 'Японский', vi: 'Вьетнамский', th: 'Тайский', id: 'Индонезийский',
  es: 'Испанский', fr: 'Французский', de: 'Немецкий' };

let cur = 'ko';
export function setUiLang(l) { cur = D[l] ? l : 'ko'; if (typeof document !== 'undefined') document.documentElement.lang = cur; }
export const uiLang = () => cur;
export function defaultUiLang() {
  const n = (navigator.language || 'ko').slice(0, 2).toLowerCase();
  return D[n] ? n : 'en';
}

export function t(key, vars = {}) {
  let s = (D[cur] && D[cur][key]) ?? D.ko[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}

export function langName(code, LANGS) {
  const L = LANGS[code];
  if (!L) return code;
  if (cur === 'ko') return L.name;
  if (cur === 'ru') return NAMES_RU[code] || L.en;
  return L.en;
}

// data-i18n="키" → 글자, data-i18n-html="키" → HTML, data-i18n-ph / data-i18n-title → 속성
export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); el.setAttribute('aria-label', t(el.dataset.i18nTitle)); });
}
